def process_file(input_path, output_path):
    """
    Обрабатывает один файл: добавляет системный промпт к каждой строке
    """
    processed_count = 0

    with open(input_path, 'r', encoding = 'utf-8') as f_in, \
        open(output_path, 'w', encoding = 'utf-8') as f_out:

        for line in f_in:
            line = line.strip()
            if not line:  # Пропускаем пустые строки
                continue

            try:
                # Парсим JSON
                data = json.loads(line)

                # Выбираем случайный системный промпт
                system_prompt = random.choice(SYSTEM_PROMPTS)

                # Добавляем системный промпт в начало request
                system_message = {"role": "system", "text": system_prompt}
                data["request"].insert(0, system_message)

                # Записываем обратно
                f_out.write(json.dumps(data, ensure_ascii = False) + '\n')
                processed_count += 1

            except json.JSONDecodeError as e:
                print(f"⚠️  Ошибка парсинга JSON в строке: {line[:50]}...")
                continue

    return processed_count


def main():
    """
    Основная функция: обрабатывает все файлы из input_folder
    """
    # Создаем выходную папку, если её нет
    output_dir = Path(OUTPUT_FOLDER)
    output_dir.mkdir(exist_ok = True)

    input_dir = Path(INPUT_FOLDER)

    # Проверяем существование входной папки
    if not input_dir.exists():
        print(f"❌ Папка {INPUT_FOLDER} не найдена!")
        print(f"Создайте папку и поместите в неё JSON-файлы.")
        return

    # Получаем все JSON-файлы
    json_files = list(input_dir.glob("*.json")) + list(input_dir.glob("*.jsonl"))

    if not json_files:
        print(f"❌ В папке {INPUT_FOLDER} не найдено JSON-файлов!")
        return

    print(f"🔍 Найдено файлов: {len(json_files)}\n")

    total_processed = 0

    # Обрабатываем каждый файл
    for input_file in json_files:
        output_file = output_dir / input_file.name

        print(f"⚙️  Обрабатываю: {input_file.name}")

        count = process_file(input_file, output_file)
        total_processed += count

        print(f"✓  Обработано строк: {count}")
        print(f"✓  Сохранено в: {output_file}\n")

    print(f"{'=' * 50}")
    print(f"✅ Готово! Всего обработано строк: {total_processed}")
    print(f"📁 Результаты в папке: {OUTPUT_FOLDER}")


if __name__ == "__main__":
    main()
